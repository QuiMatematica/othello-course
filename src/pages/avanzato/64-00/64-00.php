<p>Il sogno di tutti i giocatori di Othello alle prime armi è certamente quello di trovare una sequenza infallibile
che porti in poche mosse a eliminare tutte le pedine avversarie e a vincere quindi 64 a 0.
Ovviamente, per fortuna del gioco, questa sequenza non esiste, o quantomeno non esiste una serie di mosse
che ci garantisca una rapida vittoria indipendentemente dalle risposte avversarie.
Non si pensi, però, che non ci sia in realtà la possibilità di vincere in maniera fulminea.</p>

<p>Da uno studio fatto con il computer risulta, in effetti, che ci sono ben 57 sequenze che portano il nero
a eliminare tutte le pedine dell'avversario già alla mossa 9, e ben 89 che consentono al bianco di fare altrettanto.</p>

<p>A titolo di curiosità abbiamo pensato di proporvene qualcuna in questo capitolo scegliendo tra le varie aperture
e guardando, in qualche caso, al fattore estetico.</p>