<h2>Il <i>pattern</i></h2>

<p>Il <i>pattern</i> (diagramma <span data-board-ref="attacco-al-tre-2"></span>) che permette questo <i>tesuji</i>
    prevede la presenza di:</p>
<ul>
    <li>un tre sbilanciato da attaccare (riquadro rosso);</li>
    <li>la possibilità per l'attaccante di giocare nella casella <b>C</b> opposta (freccia gialla);</li>
    <li>l'impossibilità per l'attaccato di rispondere nelle due caselle libere rimaste (frecce viola).</li>
</ul>

