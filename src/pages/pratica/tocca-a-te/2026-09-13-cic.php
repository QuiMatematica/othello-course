    finalina. A farne le spese è stata Sandra Pistolesi, rimasta fuori di un soffio dalla sfida per il terzo posto.</p>

<p>Le finali hanno quindi definito il podio: Lai si è aggiudicato il titolo di Campione Italiano di Categoria, davanti a
