<p>La prima differenza è che il picco è più alto: abbiamo inviato al nostro corpo un'alluvione di glucosio in mezz'ora.
                Di conseguenza, il nostro pancreas inizia a produrre quantitativi spaventosi di insulina per assorbire
                quel glucosio più rapidamente. A un'ora dallo snack, c'è così tanta insulina nel nostro corpo che, anche
                dopo che l'emergenza glucosio è finita, continua ad assorbire indiscriminatamente. E così, ci eravamo
                presi uno snack per "darci la scossa," e due ore dopo stiamo peggio di prima. È il famoso crollo
                glicemico che sottovalutiamo così spesso.</p>

<p>In altre parole, tutti quei dolci e biscotti presenti nella stanza accanto al torneo all'EGP di Lucca 2025, altro non
                erano che il piano diabolico della federazione italiana di sabotare il vostro torneo proprio prima delle
                finali.</p>

<h2>La maratona Othello</h2>

<p>Quello che abbiamo visto finora, però, accade in condizioni di attività cerebrale standard. Ma che succede quando
    stiamo per ore seduti a spremerci le meningi in un torneo di Othello? Qui sotto trovate ciò che accade al nostro
    glucosio dopo aver mangiato carboidrati semplici come il pane o la pizza, mentre partecipate a un torneo.</p>

