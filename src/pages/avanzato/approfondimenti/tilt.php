    ecco che finiamo per fare 40 partite di fila proprio nel nostro momento di peggiore stato mentale. E settimane di
    crescita vengono annullate in un paio d'ore.</p>

<h2>Poteva andarci molto peggio: alcune buone notizie</h2>

<p>Il fenomeno del tilt queuing è così comune che le comunità dei giochi online ne hanno discusso a lungo. Nel mondo
    degli scacchi, ad esempio,
    <a href="https://chessbio.com/term/tilt%20queue" target="_blank" rel="noopener noreferrer">
        chessbio ha provato a spiegare il fenomeno in questo articolo <i class="bi bi-box-arrow-right"></i></a>, dando suggerimenti su
    come evitare che accada, e ci sono anche contenuti video o thread su reddit a riguardo.</p>

<p>Ma al di là della frustrazione che si prova in quel momento, il tilt queuing è davvero così grave? In realtà, è il
    caso di non farla così tragica. Prima di tutto, c'è una ragione di cui essere felici: questo stesso fenomeno accade
    (molto più spesso in realtà) nei giochi d'azzardo come il poker, e quando succede in quegli ambiti, è facile
    perdere un sacco di soldi. Chi di voi ha qualche esperienza nel mondo della finanza e degli investimenti potrà aver
    notato che accade anche lì: se avete beccato un investimento fallimentare, capita di essere spinti a trovare
    un'alternativa immediata per fare "tanti soldi in poco tempo" e recuperare la perdita, ma come potete immaginare,
    quella è proprio la condizione ideale per finire in investimenti ancora peggiori. In entrambi i casi, nel poker o
    nell'investimento dei vostri risparmi, agire mentre la vostra mente è in tilt rischia di rovinarvi. In Othello, il
    peggio che può succedervi è di perdere 200 punti di rating in un giorno. E il rating non conta nulla, giusto?</p>

<p>A parte questo, c'è un altro aspetto che vale la pena sottolineare e che può risollevarci. Quando giochiamo tutte
    quelle partite mentre il nostro cervello è un modalità default, stiamo in realtà testando <b>il nostro 
        floor</b>.</p>

<p>Nel range di lucidità che possiamo avere giocando a Othello, il picco in alto è quello che mettiamo in atto nei
    nostri migliori tornei, magari <a href="mangiare.php">dopo che
        abbiamo ingegnerizzato la nostra alimentazione alla perfezione</a>, giusto?
    Bene, il fondo del range invece è proprio il "gameplay immediato" che adottiamo quando siamo nella tilt queue. E a
    essere sinceri, migliorare il nostro floor è altrettanto importante (se non di più) che raffinare il nostro
    ceiling. Per certi versi può essere ancora più efficace: le nostre performance massime in realtà hanno un limite
    forte che risiede nel nostro talento naturale, mentre il nostro floor ha grandi margini di crescita verso
    l'alto.</p>

<h2>Migliorare il nostro istinto</h2>

<p>Ok, ma che significa migliorare il nostro floor? Significa aumentare la collezione di strumenti a cui ricorriamo
    quando il nostro cervello è incapace di ragionare in maniera profonda. In Othello, sono principalmente due: le
    sequenze mnemoniche e il riconoscimento di pattern.</p>

<p>Quando giochiamo 50 (o 200) partite in modalità tilt queue, stiamo in realtà accumulando un'immensa mole di studio
    per raffinare quelle nostre due capacità. Possiamo fare buon uso anche di quelle lunghe sessioni in cui il nostro
    rating crolla tragicamente: possiamo studiare ognuna di quelle sconfitte e vedere per esempio quanto presto siamo
    usciti fuori book, e spendere qualche minuto provando ad ampliare le nostre sequenze mnemoniche, così la prossima
    volta potremo giocare una o due mosse giuste in più senza dover ricorrere al ragionamento puro. Stessa cosa per il
    pattern recognition: spesso la mossa giusta nel medio gioco o nei finali può essere trovata attraverso "sequenze
    tipiche" che si applicano a certe situazioni, certe aree. E quando la nostra capacità di ragionamento profondo è
    limitata, sarebbe utile che quelle mosse balzino ai nostri occhi per istinto. Ovviamente ci vogliono normalmente
    anni, ma l'esperienza aiuta: studiando le mosse che il nostro istinto non ha visto in quei momenti, possiamo
    gradualmente raffinarlo.</p>

<p>Insomma, se avete passato le ultime sei ore della vostra vita in rage replay e ancora non avete trovato una
    soddisfazione che vi tiri su, guardate il lato positivo: avete la possibilità di spendere qualche minuto in più in
    fase di studio e migliorare di un po' il vostro stile di gioco quando siete in modalità pilota automatico.</p>

<h2>Il bello di essere umani</h2>

<p>Alla fine, tutto passa. Il nostro rating tornerà prima o poi quello di prima, torneremo a sentirci orgogliosi del
    livello che abbiamo raggiunto, e il tipico momento di buio passerà senza che abbiamo perso qualche migliaio di
    euro. L'essere consapevoli del modo in cui funzioniamo ci aiuta a ricordarci che ciò che viviamo è del tutto
    normale, ed è utile a ritrovare il nostro equilibrio più rapidamente.</p>

<p>Certo, magari ci arriviamo dopo che abbiamo dormito quattro ore e abbiamo sbottato ingiustificatamente a nostro
    figlio per quella tazza lasciata fuori posto dopo la colazione. Ma in fondo, siamo umani, e giochiamo a Othello
    anche per mettere alla prova le nostre abilità umane.</p>