<p>So benissimo che vi divertite a prendermi in giro quando vi do le spalle. Mi avrete visto spesso durante i tornei,
    sempre con quei comportamenti particolari, mi avrete visto sperimentare coi barattoli di marmellata e le bottiglie
    di succo, e mi avete sentito predicare qua e là su quello che assolutamente non dovete mangiare a pranzo. E so anche
    cosa state pensando in questo momento: un articolo sull'alimentazione da seguire durante un torneo? Perché, sei un
    nutrizionista?</p>

<p>No, non sono un esperto di cibo e sport. Sono solo uno che ne ha provate tante in questi anni, torneo dopo torneo,
    fino a trovare la "formula dei campioni" (non è una frase a effetto, ormai la dico ogni giorno ai miei figli quando
    hanno fame il pomeriggio). E siccome sono anche uno che scrive per passione e piacere, senza aspettare di avere il
    sacro graal della conoscenza a riguardo, ecco a voi un altro articolo di cui potevate fare a meno ma che (si spera)
    può farvi piacere leggere e può darvi spunti su cui riflettere e sperimentare: l'alimentazione ideale per un torneo
    di sport mentali.</p>

<p>E ovviamente, se da qualche parte tra voi c'è un nutrizionista, è il momento di dire la vostra.</p>

