<h2>Perché, l'alimentazione è importante per la concentrazione?</h2>

<p>Non è importante. È fondamentale.</p>

<p>Di più: scommetto che più della metà della performance che avete a un torneo è dovuta a quello che mangiate.</p>

<p>In realtà la cosa non dovrebbe stupirci. Il nostro lato più romantico ci fa credere di essere delle creature
        misteriose e speciali, capaci di questa cosa incredibile che è pensare, calcolare, e provare emozioni. Ma la
        verità è che siamo una macchina energetica che trasforma le calorie che ingeriamo in funzionalità dei nostri
        organi, con un'efficacia che dipende dal nostro stato di forma. Alla persona comune può sembrare strano fare una
        connessione tra qualcosa di astratto come le nostre emozioni o la nostra capacità di calcolo e gli aspetti
        meramente fisici del nostro corpo. Poi uno diventa appassionato di psicologia perché è affascinato dai segreti
        della nostra mente, legge Robert Sapolsky e scopre quali sono i suoi suggerimenti principali per combattere la
        depressione, i pensieri intrusivi e l'esaurimento nervoso: mangiare sano e fare attività fisica.</p>

<p>Eppure, a pensarci bene, ci potevamo arrivare. Othello, gli scacchi, o un'olimpiade di matematica, non sono
        nient'altro che uno sport. Per avere successo, il nostro cervello deve funzionare bene. Quindi, dobbiamo
        trattare il cervello per quello che è, un organo del nostro corpo, e prepararlo al meglio per la competizione.
        Molti di noi che giocano a Othello hanno la passione del jogging, corrono maratone e si allenano costantemente.
        È facile identificare certi aspetti comuni tra Othello e uno sport come la corsa: la sfida contro se stesso, la
        necessità di scavalcare i propri limiti... ma nessuno si sognerebbe mai di arrivare il giorno della maratona
        senza aver attentamente allenato polmoni e gambe e senza aver pianificato meticolosamente l'alimentazione.</p>

<p>Con Othello, è la stessa cosa. Il cervello lo alleniamo con mesi di studio e pratica e lo prepariamo con
        un'alimentazione adeguata. Altrimenti, è come mangiarsi un piatto di lasagne e poi cominciare 40 km di corsa.</p>

<h2>Allora pranzo con pizza al prossimo torneo?</h2>

<p>Tutte le volte che avete sentito che la vostra performance a un torneo di othello è andata crollando nel tempo, tutte
    le volte che vi siete sentiti meno concentrati nel pomeriggio, o nel secondo giorno, quasi sicuramente è dipeso da
    quello che avete mangiato a colazione e a pranzo. Ma se nella maratona il nemico principale è la fine delle energie
    necessarie a muovere le vostre gambe, nel caso di un torneo di othello il pericolo numero uno è il crollo
    glicemico.</p>

<p>Per performare al meglio, il cervello ha bisogno di idratazione e glucosio. Ne ha un bisogno disperato già in
            condizioni normali, e inizia a funzionare male quando ne è carente. Avete presente i vostri sbalzi d'umore
            quando avete fame? O le crisi dei vostri bambini quando escono da scuola, dopo due ore senza aver messo
            niente tra i denti? Non è altro che il cervello che ha finito il carburante. La corteccia prefrontale che
            sta gridando aiuto. E se quello è il vostro cervello in condizioni di attività regolare, figuratevi che
            succede se gli fate correre la "maratona della mente", forzandolo a concentrarsi per otto ore in un torneo
            di sport mentali.</p>

<p>Allora passo l'intero torneo a mangiare zuccheri e carboidrati, e mantengo il corpo costantemente alimentato da
            zuccheri, no?</p>

<p>Peggio: state costruendo le condizioni perfette per il classico sugar crash.</p>

<h2>L'ingegneria della nostra mente e la dannata curva del glucosio</h2>

<p>Ora facciamo un po' di geometria. Gli assi cartesiani. Questo è quello che succede al glucosio nel nostro corpo
    quando mangiamo normalissimo pane, pasta o riso, quindi carboidrati classici.</p>

