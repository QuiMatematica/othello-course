<h2>Il <i>pattern</i></h2>

<p>Anche in questo caso i <i>pattern</i> che permettono questo <i>tesuji</i> possono essere molteplici.
    Nel caso mostrato, il <i>pattern</i> (diagramma <span data-board-ref="tempo-offerto-2"></span>) che permette questo <i>tesuji</i>
    prevede la presenza di:</p>
<ul>
    <li>un accesso al bordo che offre i tempi di gioco (freccia gialla);</li>
    <li>la possibilità di attaccare il <i>cinque</i> appena formato (frecce rosse).</li>
</ul>

