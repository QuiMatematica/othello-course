<p>La colazione dei campioni fa partire al meglio il tutto, i sorsi di acqua e succo formano quelle seghettature che
                            servono come piccole scosse costanti per durare più a lungo, il pranzo senza carboidrati
                            evita un crollo più vistoso e banane e cioccolato fondente fanno il resto. Quando arrivo a
                            fine giornata, sto bene: non sento più quella sensazione di essere distrutto a fine giornata
                            come prima, ma arrivo a fine torneo in condizioni abbastanza normali. Ho corso in salita per
                            tutto il giorno ma non sento particolare fatica.</p>

<p>Questo è quello che funziona per me. Voi sentitevi liberi di sperimentare ciò che si adatta più a voi, e poi ne
                            parliamo al prossimo torneo. Il corpo umano funziona più o meno allo stesso modo per tutti,
                            ma ognuno di noi è un essere unico e può scoprire cose che funzionano più che per altri.</p>

<p>In alternativa, siete sempre liberi di guardare con occhio sospetto la mia preziosa bottiglietta del torneo e di
                            mangiarvi tranquillamente pappardelle al ragù a pranzo. E speriamo che la sesta partita del
                            giorno io la gioco contro di voi.</p>
