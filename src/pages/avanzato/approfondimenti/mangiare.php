<p>Guardate la curva in alto: quello è il sacro graal della performance cerebrale, un livello di glucosio nel sangue
                        costante e che dura per ore. Fate la colazione giusta al mattino, e la vostra mente si sentirà
                        alla grande fino a metà giornata. Se però la nostra idea di passarci "una giornata alla grande"
                        è andare a un torneo di Othello, arrivano i problemi: di nuovo la macchina a tutta velocità in
                        salita, di nuovo il glucosio bruciato a velocità impressionanti. Le cose vanno comunque molto
                        meglio: se confrontate il glucosio nelle condizioni da torneo di prima, dopo due ore eravamo nei
                        guai, qui ancora stiamo reggendo con dei livelli "normali."</p>

<p>Ma a noi che vogliamo vincere il mondiale, "normale" non basta. Noi abbiamo bisogno di dare al nostro cervello una
                        costante abbondanza di carburante per trovare le trappole che l'avversario non vede. Quindi, il
                        mix di carboidrati complessi + grassi + proteine ci dà il punto di partenza migliore, ma poi ci
                        serve un ulteriore trucchetto per percorrere l'ultimo miglio. E quello lo mettiamo in pratica
                        proprio mentre siamo seduti di fronte all'othelliera.</p>

<p>A questo punto, basta teoria. Passiamo all'esperienza. La mia, quantomeno: ecco come mangio io quando partecipo a un
                        torneo di Othello.</p>

<h2>La formula Othello</h2>

<p>Mi sveglio al mattino, possibilmente dopo una notte di 7 o 8 ore di sonno senza interruzioni. E preparo la colazione
    dei campioni: avena (meglio ancora se integrale) combinata con yogurt greco e miele. Carboidrati complessi, proteine
    e grassi. Ci sono altre combinazioni possibili, ma siccome questa ciotola piena d'energia risponde ai miei gusti,
    non ho bisogno di altro. Le quantità devono essere abbondanti: questo è il motore che parte, con questo pasto
    costruiamo le condizioni per performare al meglio per il resto della giornata.</p>

<p>Anch'io come voi ho bisogno di caffé, ma quel giorno lo prendo senza zucchero. È ancora più importante per i caffè
                            che bevo a ridosso delle partite: oggi gli zuccheri sono il nemico pubblico numero uno,
                            perché non voglio "crashes." Ho già messo il miele nella prima colazione, è già più che
                            abbastanza.</p>

<p>Un'ora prima dell'inizio del torneo, mangio una banana. La mitica banana che mangiano i maratoneti: anche quella dà
                            carboidrati complessi e zuccheri naturali, serve a "ingranare la marcia" prima dell'inizio
                            del torneo.</p>

<p>Al torneo ci arrivo con una passeggiata di circa mezz'ora (magari parcheggio un po' più lontano, o vado in metro).
                            Questo ossigena bene il corpo, evita di farmi sentire la pesantezza della digestione, e
                            rende il mio cervello più sensibile al glucosio che gli arriverà.</p>

<p>Il torneo comincia e la macchina in salita inizia a tentare di rovinare tutto quello che avevo preparato e consumare
                            tutto il glucosio che trova. Per mantenermi sveglio durante il torneo, sorseggio
                            costantemente un mix di 2/3 d'acqua e 1/3 succo di mela. Non succo puro, perché quello
                            apporterebbe troppi zuccheri e appesantirebbe la digestione, serve diluirlo in un volume
                            doppio (o più) di acqua. D'altronde il nostro cervello ha anche bisogno di tanta acqua quel
                            giorno. Mi preparo un litro di questo mix al mattino, e finisco per sorseggiarlo quasi a
                            ogni mossa. Di solito un litro è più che abbastanza per sette partite da un'ora lungo tutto
                            il giorno.</p>

<p>Alla fine della seconda partita (metà mattinata) e della quinta o sesta (metà pomeriggio), due o tre quadratini di
                            cioccolato fondente (meglio se almeno 85% di cacao). Quello serve come "scossa aggiuntiva"
                            per le seconde metà di quei periodi, che sono lontane dall'ultimo pasto.</p>

<p>A pranzo, zero carboidrati, solo proteine. Se al ristorante vi portano il pane, tirateglielo addosso. L'ideale
                            sarebbe mangiare del pesce, che contiene gli omega-3 che fanno un sacco bene al cervello.
                            Se dopo un filetto di salmone ho ancora fame, ordino un'altra porzione a base proteica. Ma
                            di solito un ordine basta, perché ho ancora la colazione dei campioni che fa il suo lavoro
                            dal mattino. Se non ho ordinato la seconda portata, alla fine del pranzo prendo un'altra
                            banana, e il gioco è fatto. Un espresso senza zucchero e il conto, grazie. E il pomeriggio
                            si continua, mix di acqua e succo e gli altri due o tre quadratini di cioccolato
    fondente.</p>

<p>Alla fine quel che succede è qualcosa del genere.</p>

