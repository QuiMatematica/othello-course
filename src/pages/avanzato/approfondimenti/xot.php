capace di navigare il caos in maniera più efficace.</p>

<h2>I tornei XOT: una sfida di abilità e visione</h2>
<p>In un torneo di Othello normale, tipicamente i giocatori hanno alcune armi a proprio vantaggio per riuscire
bene. Le abilità dell’Othello stanno alla base, ovviamente, ma accanto a queste c’è la possibilità di
effettuare una preparazione particolare per affinare alcune altre armi, che possono permetterti di riuscire
meglio.</p>

<p>La questione emersa recentemente riguardo
    <a href="https://www.worldothello.org/news/445/the-catch-22-perfect-storm" target="_blank" rel="noopener noreferrer">la
        memorizzazione di lunghe sequenze perfette</a> è solo una
di quelle armi. Usare la memoria per ridurre la necessità di ragionamento, per risparmiare tempo, e per
reggere le dinamiche di gioco a cui alcuni top players ti costringono, è una delle componenti che si
possono preparare con ore di studio prima di un torneo importante. Non richiede abilità Othello in senso
stretto, ma soprattutto memoria, e può darti un vantaggio oggettivo, ovviamente. Per alcuni fa parte del
gioco, per altri può renderlo noioso da vedere dall’esterno, qui non affronteremo la questione.</p>
<p>Altri modi di prepararsi a un torneo sono studiare alcuni giocatori specifici (magari provando a condurli su
un territorio ben preciso in base alle aperture che solitamente giocano) o preparare aperture alternative
che possano sorprendere gli avversari. Messo tutto in conto, abbiamo una conclusione ovvia: un
giocatore può avere una prestazione migliore a un torneo se spende ore ogni giorno a prepararsi per
quella competizione. Più lunga è la preparazione, più grossi i potenziali vantaggi che se ne possono
ottenere rispetto a uno che si è preparato meno, o che non si prepara affatto. Da questo punto di vista,
possiamo dire che un torneo di Othello standard premia il giocatore con la più alta somma di abilità
naturali + preparazione. E se ci pensiamo bene, ha perfettamente senso: in ogni sport al mondo il
successo di un atleta dipende non solo dal suo talento naturale ma anche dallo sforzo che ci ha messo
ad allenarsi prima di una specifica competizione, ed è giusto che quello sforzo vada premiato.</p>
<p>Con l’Othello XOT, invece, la preparazione non può esserci (partiamo dal presupposto che l’improbabile
intenzione di memorizzare tutte le aperture XOT esistenti e studiarne le continuazioni sia un’impresa
inumana e complessivamente inefficace in termini di rapporto sforzo/risultato). Senza la preparazione,
Othello XOT diventa tendenzialmente una sfida di pure abilità, puro talento naturale. Il che è affascinante
da un punto di vista strettamente teorico, ed è comprensibile che alcuni abbiano iniziato ad amarlo,
accanto ad altri che preferiscono ancora avere quegli altri elementi a contorno che diano più controllo
alla cosa.</p>
<p>Abbiamo trovato la soluzione perfetta per il futuro dell’Othello allora? Si e no, in realtà. Perché accanto al
piacere di una competizione fatta di sole abilità c’è un aspetto nascosto insidioso...</p>

<h2>Il peso del caos</h2>
<p>Othello XOT ha una componente casuale molto più pesante. Il caos sull’Othelliera non è l’eccezione, è la
regola. E il caos genera ovviamente situazioni più imprevedibili, che possono portare a una sconfitta
anche se hai messo in gioco tutte le Othello-skills alla perfezione. Il che spiega perché al primo europeo
XOT abbiamo assistito a punteggi mediamente più bassi rispetto ai tornei normali. Si perde
generalmente di più, insomma. E non è qualcosa che puoi prevenire con maggiore preparazione o ore di
studio.</p>
<p>Giocare in modalità XOT ti mette di fronte spessissimo a situazioni scomode. Prendere un bordo molto
presto, giocare fuori dagli “sweet sixteen” in anticipo, avere una X-square già occupata o essere costretti
a giocarla prestissimo... sono tutte cose che possono accadere anche nell’Othello normale, ma di solito lì
abbiamo libertà di scelta. Possiamo scegliere continuazioni ancora accettabili in direzioni più standard, o
possiamo scegliere di cambiare apertura prima, per evitare di finire nelle posizioni in cui non abbiamo
confidenza.</p>
<p>Nel mondo XOT, invece, spesso l’alternativa non c’è, o c’è ma porta a uno svantaggio ancora peggiore.
Capita spesso che ci sia una sola mossa che ci faccia rimanere a galla, e se ci capita di non vederla o di
non volerla perché porta a posizioni troppo assurde, si rischia che la partita sia finita con largo anticipo.</p>

