<p>Questo <i>tesuji</i> è estremamente semplice, tuttavia spesso sono le cose più semplici che ci sfuggono.</p>

<p>Nel diagramma <span data-board-ref="tempo-offerto-1"></span> il nero ha un'unica mossa tranquilla: <b>A4</b>.
Apparentemente questa mossa concede all'avversario due tempi di gioco: in <b>A2</b> e in <b>A7</b>.
    Ma dopo <b>A2</b> il nero può attaccare il <i>cinque</i> appena formatosi prima che diventi un <i>sei</i>.</p>

