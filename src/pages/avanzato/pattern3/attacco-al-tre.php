<p>Talvolta si tende a sottovalutare la pericolosità di un bordo sbilanciato e in particolare di un
<i>tre sbilanciato</i>.</p>

<p>In particolari situazioni, con il controllo delle giuste linee, un tre sbilanciato può essere attaccato in modo
    simile a quanto abbiamo già visto per le
    <a href="../../intermedio/altri-attacchi-ai-bordi/attacchi-alle-caselle-c.php">caselle C isolate</a>.
    Questo tipo di attacco garantisce l'accesso all'angolo
e il controllo di buona parte del bordo. Inoltre il giocatore attaccante guadagna due tempi di gioco.</p>

