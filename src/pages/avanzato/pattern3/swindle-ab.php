<h2>Il <i>pattern</i></h2>

<p>I <i>pattern</i> che permettono questo <i>tesuji</i> possono essere molto vari. La caratteristica comune è che,
    dopo la mossa di attacco, l'attaccato non ha accesso alla casella B rimasta libera sul bordo
    (frecce gialle nel diagramma <span data-board-ref="swindle-ab-3"></span>). &Egrave; questa
    caratteristica che costringe l'attaccato a scegliere tra sbilanciarsi o perdere due tempi di gioco.</p>

