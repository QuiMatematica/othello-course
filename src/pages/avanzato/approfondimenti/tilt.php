    momento.</p>

<h2>Il glitch nel nostro cervello: cosa succede quando qualcosa va storto</h2>

<p>Ti prendi una pausa e fai partire una partita online. La partita finisce e non sei per niente soddisfatto: per
    qualche motivo, non hai visto qualcosa che avresti dovuto vedere, o sei finito in una situazione disperata senza
    una ragione chiara. Se la tua mente è lucida, riesci a fare spallucce e non farti trascinare troppo in basso da una
    singola sconfitta. Però poi magari ne giochi altre due, e sorte vuole che la situazione si ripeta.</p>

<p>Dopo un po', rimanere lucidi diventa impossibile. È colpa della biologia: il nostro corpo sta andando a quello che
    scientificamente si chiama <b>dopamine crash</b>. I livelli di dopamina crollano rapidamente, e la nostra mente entra
    nel panico. Abbiamo provato una straordinaria ondata di insoddisfazione, e il nostro cervello ora ha la necessità
    di trovare un qualcosa che ci fornisca un picco immediato, per provare a dimenticare quanto successo. E siccome
    siamo probabilmente in una di quelle app online col matching automatico, è istintivo premere su "play again" dopo
    un secondo, sperando che la sorte cambi.</p>

<p>Per molti, la frustrazione è semplicemente dovuta al vedere il proprio rating online crollare. Per altri
    (personalmente sono tra questi) il rating conta poco, ma il problema sta nell'importanza di ritrovare la propria
    brillantezza: è necessario arrivare ad una partita che finisca con la sensazione di aver ritrovato "il tuo tocco."
    Il problema però lo capite da soli: stiamo inseguendo una performance soddisfacente proprio mentre il nostro
    cervello ha perso completamente il suo focus. Perché - la legge di Murphy - nel momento in cui giochiamo venti
    partite in tilt queueing, la nostra capacità di concentrarci è in realtà compromessa: un altro effetto diretto
    del dopamine crush.</p>

<p>Il risultato è che finiamo per giocare quella lunga serie di partite solo con una delle due parti del nostro
    ragionamento. Ricordate quando abbiamo parlato dei <a href="contare.php">due approcci mentali che usiamo quando
        giochiamo a Othello</a>? Li
    abbiamo battezzati "approccio posizionale" e "approccio predittivo," ma non rappresentano altro che la differenza
    tra il "giocare di istinto" e il "calcolare ogni continuazione con la massima profondità di cui siamo capaci."
    Ecco, quando stiamo in tilt queuing, la nostra metà calcolatrice è completamente andata. Stiamo giocando basandoci
    puramente su memoria, pattern e mosse istintive, ossia il funzionamento del nostro gameplay di default, quando il
    cervello non è in condizioni adeguate per pensieri complessi.</p>

