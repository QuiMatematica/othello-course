<p>Se l'avversario non ha modo di tagliare la diagonale, allora la diagonale è sicura. Ma potrebbe bastare meno.</p>

<p>Può bastare che per ogni taglio esista un'opportuna contromossa.</p>

<p>Chiaramente questa situazione è più delicata: vanno analizzati tutti i possibili tagli e vanno trovate tutte le
opportune contromosse. &Egrave; sufficiente che un taglio non abbia la contromossa per rendere inattuabile il
    <i>tesuji</i>.</p>

<p>Ma nella posizione del diagramma <span data-board-ref="diagonale-sicura-2"></span> se il nero gioca in <b>B2</b>,
il bianco ha un solo modo per tagliare la diagonale ed è facile trovare la contromossa corretta.</p>

