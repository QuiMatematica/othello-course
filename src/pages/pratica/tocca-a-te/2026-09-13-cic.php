<p>Fin dai primi turni è emerso un sostanziale equilibrio nelle posizioni di vertice, con Lai, Barsotti, Pistolesi,
    Landini e Turato a darsi battaglia per rimanere nelle parti alte della classifica. Più difficile, invece, il cammino
    per Luzi, Gazzetti e Salvo (figlio, uno dei tanti).</p>

