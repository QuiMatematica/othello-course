<p>È più o meno come ci aspettavamo: mangiamo, i livelli di glucosio nel nostro corpo aumentano, dopo circa un'ora
                raggiungono il picco, dopo circa due ore tornano com'erano prima. Questo è quello che ci succede tra un
                pasto e l'altro in condizioni di attività mentale normale, mentre svolgiamo le nostre attività
                quotidiane.</p>

<p>Ora, vediamo che succede (sempre in condizioni di attività normale) se ci mangiamo uno snack dolce.</p>

