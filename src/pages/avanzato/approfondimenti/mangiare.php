<p>Ma come, più glucosio di prima a parità di alimentazione? Sì, per un motivo più specifico: l'adrenalina del torneo
                    spinge il nostro fegato a bruciare le riserve di glicogeno accumulate in passato, quindi aggiunge
                    carburante per il nostro cervello. Il nostro cervello, però, non sta facendo una passeggiata lungo
                    il lago: sta correndo a tutta velocità in salita per un'ora. Il consumo di glucosio è rapidissimo, e
                    quindi il crollo dopo il pasto è più problematico, simile al sugar crash che proviamo dopo i famosi
                    biscottini.</p>

<p>A questo aggiungete un altro elemento: se mangiate una pizza a pranzo, fate partire un lungo e dispendiosissimo
                    processo di digestione, che dirotterà il sangue verso l'apparato digerente. È una delle attività
                    energeticamente più impegnative che il corpo umano possa eseguire. Quindi, mentre la vostra
                    corteccia prefrontale ha un disperato bisogno di flusso sanguigno ricco di glucosio, voi tirate il
                    freno a mano alla vostra auto in salita e gli fate digerire una prosciutto e funghi. E così, le
                    ultime partite della giornata le giocate nelle condizioni peggiori possibili.</p>

<p>Qui però sembra un rompicapo senza soluzioni. E in parte lo è. Però, possiamo fare molto per metterci in condizioni
                    molto più adatte a un torneo.</p>

<h2>L'alimentazione da campioni</h2>

<p>Il segreto è mangiare carboidrati complessi, e unirli a un consistente apporto di proteine e grassi. I carboidrati
    complessi come pasta o pane integrale o cereali richiedono più tempo per essere scomposti, allungando così la curva
    glicemica. Inoltre, se combinati con grassi e proteine, l'apparato digerente rallenta ancora di più il processo
    digestivo, facendo in modo che la curva glicemica complessiva abbia un respiro molto più lungo. E questo è quel che
    succede:</p>

